#include <stdio.h>
#include <stdint.h>

int rle_compress(const uint8_t* in, size_t in_len, uint8_t* out, size_t out_max) {
    size_t out_idx = 0;
    size_t i = 0;

    while (i < in_len) {
        uint8_t val = in[i];
        size_t run = 1;
        while (i + run < in_len && in[i + run] == val && run < 127) {
            run++;
        }

        if (run >= 3) {
            // Compress run
            if (out_idx + 2 > out_max) return -1;
            out[out_idx++] = (uint8_t)(run | 0x80);
            out[out_idx++] = val;
            i += run;
        } else {
            // Literal block - collect until we hit a good run
            size_t lit_start = i;
            size_t lit_len = 0;

            while (i < in_len && lit_len < 127) {
                // Look ahead for run of 3+
                size_t next_run = 1;
                uint8_t next_val = in[i];
                while (i + next_run < in_len && in[i + next_run] == next_val && next_run < 3) {
                    next_run++;
                }
                if (next_run >= 3) break;

                lit_len++;
                i++;
            }

            if (lit_len > 0) {
                if (out_idx + 1 + lit_len > out_max) return -1;
                out[out_idx++] = (uint8_t)lit_len;   // literal count
                for (size_t j = 0; j < lit_len; j++) {
                    out[out_idx++] = in[lit_start + j];
                }
            }
        }
    }
    return (int)out_idx;
}

int rle_decompress(const uint8_t* in, size_t in_len, uint8_t* out, size_t out_max) {
    size_t out_idx = 0;
    size_t i = 0;

    while (i < in_len) {
        uint8_t count = in[i++];

        if (count & 0x80) {
            // Run
            uint8_t val = in[i++];
            uint8_t real_count = count & 0x7F;
            if (out_idx + real_count > out_max) return -1;
            for (uint8_t j = 0; j < real_count; j++) {
                out[out_idx++] = val;
            }
        } else {
            // Literal block
            if (i + count > in_len || out_idx + count > out_max) return -1;
            for (uint8_t j = 0; j < count; j++) {
                out[out_idx++] = in[i++];
            }
        }
    }
    return (int)out_idx;
}

void print_bytes(const char* label, const uint8_t* data, size_t len) {
    printf("%s (%zu bytes): ", label, len);
    for (size_t k = 0; k < len; k++) {
        printf("0x%02X ", data[k]);
        if ((k+1) % 16 == 0) printf("\n                      ");
    }
    printf("\n");
}

